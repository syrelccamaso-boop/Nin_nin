_roles_table_cache: dict | None = None


def _parse_id(value: str):
    value = (value or "").strip()

    if value.lstrip("-").isdigit():
        return int(value)

    return value


def _roles_from_env() -> dict:
    """
    Read optional ROLE_ID_<NAME> environment variables.

    Example:

        ROLE_ID_TEACHER=1
        ROLE_ID_TECHNICIAN=2
    """

    roles: dict = {}

    for key, value in os.environ.items():

        if key.upper().startswith("ROLE_ID_") and value.strip():

            name = key[len("ROLE_ID_") :].replace("_", " ").title()

            roles[name] = _parse_id(value)

    return roles


def _roles_from_table() -> dict:
    """
    Load roles from the actual Role table.

    Schema:

        Role.RoleId bigint PRIMARY KEY
        Role.Role   text NOT NULL
    """

    global _roles_table_cache

    if _roles_table_cache is not None:
        return _roles_table_cache

    _roles_table_cache = {}

    try:
        response = (
            get_client().table(ROLE_TABLE).select("RoleId,Role").limit(100).execute()
        )

        rows = response.data or []

        for row in rows:

            role_id = row.get("RoleId")
            role_name = row.get("Role")

            if role_id is None or not role_name:
                continue

            _roles_table_cache[str(role_name).strip()] = role_id

        if _roles_table_cache:
            logger.info(
                "Loaded %d roles from the Role table.",
                len(_roles_table_cache),
            )

    except Exception as error:
        logger.warning(
            "Could not load roles from the Role table: %s",
            error_text(error),
        )

    return _roles_table_cache


def _all_roles() -> dict:
    """
    Database Role table is the primary source.

    Environment variables are retained as an optional
    compatibility fallback/override.
    """

    roles = dict(_roles_from_table())
    roles.update(_roles_from_env())

    return roles


def role_id_for(role: str):
    """
    Return RoleId for a role name.

    Comparison is case-insensitive.
    """

    wanted = (role or "").strip().lower()

    if not wanted:
        return None

    for name, role_id in _all_roles().items():

        if name.lower() == wanted:
            return role_id

    return None


def role_name_for(role_id) -> str:
    """
    Return Role.Role for a given RoleId.
    """

    if role_id is None:
        return ""

    for name, value in _all_roles().items():

        if str(value) == str(role_id):
            return name

    return ""


def roles_problem() -> str | None:
    """
    Check that the application-required roles exist.

    This does not create or modify roles.
    """

    missing = []

    for role_name in (
        "TEACHER",
        "TECHNICIAN",
    ):

        if role_id_for(role_name) is None:
            missing.append(role_name.title())

    if missing:

        env_names = [f"ROLE_ID_{name.upper()}" for name in missing]

        return (
            "No RoleId configured for: "
            + ", ".join(missing)
            + ". Ensure the Role table contains these roles"
            + " or configure "
            + ", ".join(env_names)
            + " in .env."
        )

    return None


def invalidate_roles_cache() -> None:
    """Force the next role lookup to reload Role."""

    global _roles_table_cache

    _roles_table_cache = None


