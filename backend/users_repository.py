def get_user_by_email(
    email: str,
) -> dict | None:
    """
    Return the raw Users row for an email.

    Exact match is attempted first.
    A case-insensitive fallback is then used.
    """

    email = normalize_email(email)

    if not email:
        return None

    def query(client):

        response = (
            client.table(TABLE)
            .select(SELECT_COLUMNS)
            .eq("Email", email)
            .limit(1)
            .execute()
        )

        if response.data:
            return response.data[0]

        response = (
            client.table(TABLE)
            .select(SELECT_COLUMNS)
            .ilike(
                "Email",
                _escape_like(email),
            )
            .limit(1)
            .execute()
        )

        return response.data[0] if response.data else None

    return _run(
        "looking up a user by email",
        query,
    )


def get_user_by_id(
    user_id,
) -> dict | None:
    """
    Return a Users row by Users.UserId.

    UserId is a PostgreSQL bigint.
    It is NOT the Supabase Auth UUID.
    """

    def query(client):

        response = (
            client.table(TABLE)
            .select(SELECT_COLUMNS)
            .eq("UserId", user_id)
            .limit(1)
            .execute()
        )

        return response.data[0] if response.data else None

    return _run(
        "looking up a user by id",
        query,
    )


def get_user_by_auth_id(
    auth_id: str,
) -> dict | None:
    """
    Return the Users row linked to auth.users.id.

    Relationship:

        auth.users.id
              ↓
        Users.AuthId
    """

    auth_id = str(auth_id or "").strip()

    if not is_uuid(auth_id):
        return None

    def query(client):

        response = (
            client.table(TABLE)
            .select(SELECT_COLUMNS)
            .eq(
                AUTH_ID_COLUMN,
                auth_id,
            )
            .limit(1)
            .execute()
        )

        return response.data[0] if response.data else None

    return _run(
        "looking up a user by AuthId",
        query,
    )


def email_exists(
    email: str,
) -> bool:
    return get_user_by_email(email) is not None


def list_users(
    status: str | None = None,
    role: str | None = None,
    search_term: str | None = None,
    department: str | None = None,
    limit: int = 500,
) -> list[dict]:
    """
    Return raw Users rows, newest first.

    Optional filters:

        status
        role
        search_term
        department
    """

    def query(client):

        request = client.table(TABLE).select(SELECT_COLUMNS)

        if status:

            request = request.ilike(
                "Status",
                _escape_like(status.strip()),
            )

        if role:

            role_id = role_id_for(role)

            if role_id is None:
                return []

            request = request.eq(
                "RoleId",
                role_id,
            )

        if department:

            request = request.ilike(
                "Department",
                f"%{_escape_like(department.strip())}%",
            )

        if search_term:

            term = f"%{_escape_like(search_term.strip())}%"

            request = request.or_(
                ",".join(
                    [
                        f"FirstName.ilike.{term}",
                        f"LastName.ilike.{term}",
                        f"Email.ilike.{term}",
                        f"Department.ilike.{term}",
                    ]
                )
            )

        response = (
            request.order(
                "CreatedAt",
                desc=True,
            )
            .limit(
                max(
                    1,
                    min(
                        int(limit),
                        1000,
                    ),
                )
            )
            .execute()
        )

        return response.data or []

    return _run(
        "listing users",
        query,
    )


def search_users(
    search_term: str | None = None,
    status: str | None = None,
    role: str | None = None,
    department: str | None = None,
    limit: int = 200,
) -> list[dict]:
    """
    Search Users and return application-level user dictionaries.

    This intentionally calls list_users() only once.
    """

    rows = list_users(
        status=status,
        role=role,
        search_term=search_term,
        department=department,
        limit=limit,
    )

    return [to_app_user(row) for row in rows if row]


def check_connection() -> str | None:
    """
    Return None if Users can be read,
    otherwise return a short diagnostic.
    """

    try:

        _run(
            "checking the database connection",
            lambda client: (client.table(TABLE).select("UserId").limit(1).execute()),
        )

        return None

    except DatabaseError as error:

        return error.detail[:300] or str(error)


