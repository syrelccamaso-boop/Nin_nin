def status_value(
    canonical: str,
) -> str:
    """
    Normalize an application status.

    The supplied database schema does NOT define a CHECK
    constraint for Users.Status, so this function does not
    invent a fixed list of valid database statuses.

    Existing casing is preserved where possible.
    """

    canonical = (canonical or "").strip().lower()

    if not canonical:
        return "active"

    try:

        rows = _run(
            "reading existing Status values",
            lambda client: (
                client.table(TABLE).select("Status").limit(20).execute().data or []
            ),
        )

    except DatabaseError:

        return canonical

    samples = [str(row.get("Status") or "") for row in rows if row.get("Status")]

    if any(sample.isupper() for sample in samples):
        return canonical.upper()

    if any(sample[:1].isupper() for sample in samples):
        return canonical.capitalize()

    return canonical


