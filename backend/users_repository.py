"""
CRUD functions for the existing Supabase tables "Users" and "Role".

Database schema source of truth:

Users
-----
UserId          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY
Email           text NOT NULL
LastName        text NOT NULL
FirstName       text NOT NULL
CreatedAt       timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
Department      text NOT NULL
ContactNumber   text NULL
UpdatedAt       timestamptz DEFAULT CURRENT_TIMESTAMP
RoleId          bigint NOT NULL FK -> Role.RoleId
AuthId          uuid UNIQUE FK -> auth.users(id)
Status          text NOT NULL DEFAULT 'active'
DateConfirmed   timestamptz NULL  (set once, when a pending account is confirmed)

Role
----
RoleId          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY
Role            text NOT NULL

Important:
- UserId is generated by PostgreSQL and is never supplied by the application.
- AuthId stores auth.users.id.
- RoleId is the only role field stored in Users.
- Role name is stored in Role.Role.
- Passwords are NOT stored in Users.
"""

from __future__ import annotations

import logging
import os
import re
from datetime import datetime, timezone

from .database import DatabaseConfigError, get_client

logger = logging.getLogger("centrum.users")


# =========================================================
# TABLE / COLUMN CONSTANTS
# =========================================================

TABLE = "Users"
ROLE_TABLE = "Role"

COLUMNS = (
    "UserId",
    "Email",
    "LastName",
    "FirstName",
    "CreatedAt",
    "Department",
    "ContactNumber",
    "UpdatedAt",
    "RoleId",
    "AuthId",
    "Status",
    "DateConfirmed",
)

SELECT_COLUMNS = ",".join(COLUMNS)

# Actual foreign-key column linking Users to auth.users(id).
AUTH_ID_COLUMN = "AuthId"


# =========================================================
# FIELD MAP
# =========================================================

FIELD_MAP = {
    "user_id": "UserId",
    "email": "Email",
    "first_name": "FirstName",
    "last_name": "LastName",
    "created_at": "CreatedAt",
    "department": "Department",
    "contact_number": "ContactNumber",
    "updated_at": "UpdatedAt",
    "role_id": "RoleId",
    "auth_id": "AuthId",
    "status": "Status",
    # Read-only for the app: NOT in UPDATABLE. Set only by update_status()
    # when a pending account is confirmed.
    "date_confirmed": "DateConfirmed",
}


# UserId, AuthId and CreatedAt are not directly editable
# through normal profile updates.
UPDATABLE = {
    "email",
    "first_name",
    "last_name",
    "department",
    "contact_number",
    "status",
    "role_id",
    "role",
}


_UUID_RE = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-" r"[0-9a-f]{4}-[0-9a-f]{12}$",
    re.IGNORECASE,
)


