def update_user(
    user_id,
    changes: dict,
) -> dict | None:
    """
    Update allowed Users fields.

    UserId, AuthId, and CreatedAt are not normally modified
    through this function.

    UpdatedAt is automatically maintained.
    """

    unknown = set(changes) - UPDATABLE

    if unknown:

        raise ValueError("These fields can't be updated: " f"{sorted(unknown)}")

    if not changes:
        return get_user_by_id(user_id)

    changes = dict(changes)

    # -----------------------------------------------------
    # Convert human-readable role to RoleId.
    # -----------------------------------------------------

    if "role" in changes:

        role_name = changes.pop("role")

        role_id = role_id_for(role_name)

        if role_id is None:

            raise ValueError(f"Unknown role: {role_name!r}")

        changes["role_id"] = role_id

    row = _to_columns(changes)

    # -----------------------------------------------------
    # Email uniqueness.
    # -----------------------------------------------------

    if "Email" in row:

        row["Email"] = normalize_email(row["Email"])

        other = get_user_by_email(row["Email"])

        if other and str(other.get("UserId")) != str(user_id):
            raise DatabaseError(
                "An account with this email already exists.",
                code="duplicate",
            )

    # -----------------------------------------------------
    # Required fields.
    # -----------------------------------------------------

    if "FirstName" in row:

        if not str(row["FirstName"]).strip():

            raise ValueError("First name cannot be empty.")

        row["FirstName"] = str(row["FirstName"]).strip()

    if "LastName" in row:

        if not str(row["LastName"]).strip():

            raise ValueError("Last name cannot be empty.")

        row["LastName"] = str(row["LastName"]).strip()

    if "Department" in row:

        if not str(row["Department"]).strip():

            raise ValueError("Department cannot be empty.")

        row["Department"] = str(row["Department"]).strip()

    if "ContactNumber" in row:

        row["ContactNumber"] = str(row["ContactNumber"]).strip() or None

    # -----------------------------------------------------
    # UpdatedAt is maintained whenever a record changes.
    # -----------------------------------------------------

    row["UpdatedAt"] = datetime.now(timezone.utc).isoformat()

    def update(client):

        response = client.table(TABLE).update(row).eq("UserId", user_id).execute()

        return response.data[0] if response.data else None

    return _run(
        "updating a user",
        update,
    )


def update_status(
    user_id,
    status: str,
) -> dict | None:
    """
    Update Users.Status.

    When a PENDING account becomes active (the admin confirms it),
    Users.DateConfirmed is set to the current time - but only if it is
    still NULL, so an existing confirmation date is never overwritten
    (reactivating a deactivated account does not touch it).
    """

    value = status_value(status)

    if value.strip().lower() != "active":
        return update_user(user_id, {"status": value})

    current = get_user_by_id(user_id)

    if current is None:
        return None

    was_pending = str(current.get("Status") or "").strip().lower() == "pending"

    if not was_pending or current.get("DateConfirmed"):
        return update_user(user_id, {"status": value})

    now = datetime.now(timezone.utc).isoformat()

    def confirm(client):

        response = (
            client.table(TABLE)
            .update({"Status": value, "DateConfirmed": now, "UpdatedAt": now})
            .eq("UserId", user_id)
            .is_("DateConfirmed", "null")
            .execute()
        )

        return response.data[0] if response.data else None

    row = _run("confirming a user", confirm)

    # Someone else set DateConfirmed in the meantime: keep their date,
    # just change the status.
    return row or update_user(user_id, {"status": value})


