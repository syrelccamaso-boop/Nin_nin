def create_user(
    email: str,
    first_name: str,
    last_name: str,
    department: str,
    role: str,
    status: str,
    contact_number: str = "",
    auth_id=None,
    role_id=None,
) -> dict:
    """
    Create a Users row.

    IMPORTANT:

    UserId is GENERATED ALWAYS AS IDENTITY.

    Therefore:
        UserId is NEVER included in INSERT.

    AuthId stores auth.users.id.
    RoleId references Role.RoleId.
    CreatedAt and UpdatedAt use database/application timestamps.
    """

    email = normalize_email(email)

    if not email:
        raise DatabaseError(
            "Email is required.",
            code="validation",
        )

    if not first_name or not first_name.strip():
        raise DatabaseError(
            "First name is required.",
            code="validation",
        )

    if not last_name or not last_name.strip():
        raise DatabaseError(
            "Last name is required.",
            code="validation",
        )

    if not department or not department.strip():
        raise DatabaseError(
            "Department is required.",
            code="validation",
        )

    if email_exists(email):
        raise DatabaseError(
            "An account with this email already exists.",
            code="duplicate",
        )

    if role_id is None:
        role_id = role_id_for(role)

    if role_id is None:
        logger.error(
            "No RoleId found for role %r.",
            role,
        )

        raise DatabaseError(
            "Registration isn't set up for this role yet. "
            "Please contact the administrator.",
            code="role_config",
        )

    row = {
        "Email": email,
        "FirstName": first_name.strip(),
        "LastName": last_name.strip(),
        "Department": department.strip(),
        "ContactNumber": (contact_number or "").strip() or None,
        "Status": (status or "active").strip(),
        "RoleId": role_id,
    }

    # AuthId is the FK to auth.users(id).
    if auth_id is not None:

        auth_id = str(auth_id)

        if not is_uuid(auth_id):
            raise DatabaseError(
                "The Supabase Auth ID is invalid.",
                code="invalid_auth_id",
            )

        row[AUTH_ID_COLUMN] = auth_id

    # Do NOT include:
    #
    # UserId
    #
    # CreatedAt
    #
    # UpdatedAt
    #
    # PostgreSQL supplies those values using the schema defaults.

    def insert(client):

        response = client.table(TABLE).insert(row).execute()

        if response.data:
            return response.data[0]

        # Supabase normally returns the inserted row.
        # If it doesn't, retrieve it using AuthId or Email.
        if auth_id:
            response = (
                client.table(TABLE)
                .select(SELECT_COLUMNS)
                .eq(AUTH_ID_COLUMN, auth_id)
                .limit(1)
                .execute()
            )

        else:
            response = (
                client.table(TABLE)
                .select(SELECT_COLUMNS)
                .eq("Email", email)
                .limit(1)
                .execute()
            )

        return response.data[0] if response.data else None

    created = _run(
        "creating a user",
        insert,
    )

    if not created:
        raise DatabaseError(
            "The user account was created but "
            "the application profile could not be retrieved.",
            code="create_no_row",
        )

    return created


