def delete_user(
    user_id,
) -> bool:
    """
    Delete a Users row.

    The database schema contains multiple foreign keys
    pointing to Users.UserId.

    Therefore, deletion may fail if related records exist
    and those relationships do not use ON DELETE CASCADE.

    This function does not manually delete unrelated records.
    """

    def delete(client):

        response = client.table(TABLE).delete().eq("UserId", user_id).execute()

