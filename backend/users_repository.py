def normalize_email(email: str) -> str:
    return (email or "").strip().lower()


def is_uuid(value) -> bool:
    return bool(_UUID_RE.match(str(value or "")))


def _escape_like(value: str) -> str:
    return value.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")


def to_app_user(row: dict | None) -> dict | None:
    """
    Convert a raw Users row into the application-level
    snake_case user dictionary.

    Database source:
        Users.UserId
        Users.Email
        Users.FirstName
        Users.LastName
        Users.Department
        Users.ContactNumber
        Users.Status
        Users.RoleId
        Users.AuthId
        Users.CreatedAt
        Users.UpdatedAt
    """

    if not row:
        return None

    role_id = row.get("RoleId")

    return {
        # Application primary key.
        # This is Users.UserId, NOT auth.users.id.
        "id": row.get("UserId"),
        "user_id": row.get("UserId"),
        "email": row.get("Email") or "",
        "first_name": row.get("FirstName") or "",
        "last_name": row.get("LastName") or "",
        "role_id": role_id,
        "role": role_name_for(role_id),
        "department": row.get("Department") or "",
        "contact_number": row.get("ContactNumber") or "",
        "status": (row.get("Status") or "").strip().lower(),
        "created_at": row.get("CreatedAt"),
        "updated_at": row.get("UpdatedAt"),
        # Users.DateConfirmed as stored (None when NULL).
        "date_confirmed": row.get("DateConfirmed"),
        # Supabase Auth UUID.
        "auth_id": row.get(AUTH_ID_COLUMN),
    }


def _to_columns(fields: dict) -> dict:
    """
    Convert application snake_case fields into
    actual database column names.

    Unknown fields are rejected rather than silently
    inserting nonexistent database columns.
    """

    row = {}

    for key, value in fields.items():
        column = FIELD_MAP.get(key)

        if column is None:
            raise ValueError(f"Unknown field: {key!r}")

        row[column] = value

    return row


